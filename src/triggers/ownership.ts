/**
 * Who a trigger's turns act as in Bases.
 *
 * A trigger is owned by the turn that created it: the operator, or the
 * contact who asked for it. Its agent turns then act in Bases as that owner,
 * the operator or the contact through their own `ravi link`.
 *
 * The owner is written once, when the trigger is created, and only ever
 * taken away afterwards. Anyone but the owner who changes what the trigger
 * runs, which events it sees, which agent or session it uses or where it
 * answers leaves it with no owner (`triggers-db.ts`); nobody takes a trigger
 * over by editing it, the operator included, because every one of those
 * fields shapes a turn that carries text other people wrote. Turning a
 * trigger on keeps its owner for the owner and for the operator, who arms it
 * without owning it. A trigger with no owner (written before owners existed,
 * generated by Ravi, or changed by someone else) acts as nobody. To give one
 * an owner, create it again.
 *
 * The owner's authority is lent only where nobody else is part of the turn:
 * in the trigger's own session (`--session isolated`, the one session only
 * that trigger's fires enter, which goes by its key as its one name), as a
 * turn of its own, answering to no chat. A session anyone can name (the
 * agent's main one, a chat's, a named or templated one) inherits whatever was
 * keyed to that name and takes other triggers' fires, so it never lends.
 *
 * Only Bases reads this. Personal connectors, Knowledge, Pages access and
 * cloud runs keep refusing trigger turns, and no owner is enforced on a shell
 * trigger.
 */

import {
  CRON_OPERATOR_OWNER,
  cronOwnerActsAsOperator,
  resolveCronOwnerPrincipalForCurrentTurn,
  type ConnectorTurnDeps,
} from "../link/connector-turn.js";
import {
  isPersonPrincipal,
  isTriggerOwnSessionKey,
  triggerIsolatedSessionKey,
  triggerOfSessionKey,
  type TriggerRunAuthority,
} from "./authority.js";
import { getSession, resolveSession } from "../router/sessions.js";
import { isLegacySessionTarget, isSessionNameTemplate, type Trigger } from "./types.js";

/** Shown for a trigger with no owner. */
export const TRIGGER_UNKNOWN_OWNER = "unknown";

/**
 * `triggers set` keys that never touch the owner, whoever sets them: how
 * often the trigger fires and how long its shell command may run.
 */
export const TRIGGER_OWNER_NEUTRAL_SET_KEYS: ReadonlySet<string> = new Set(["cooldown", "timeout"]);

/** "Runs as" for a trigger. */
export function triggerRunsAs(trigger: Pick<Trigger, "ownerPrincipal">): string {
  return trigger.ownerPrincipal?.trim() || TRIGGER_UNKNOWN_OWNER;
}

/**
 * Whether a trigger with this owner acts as the operator in Bases. Unlike a
 * cron job, no owner is not the operator: trigger turns never acted as the
 * operator there, so an older row gains nothing.
 */
export function triggerOwnerActsAsOperator(
  ownerPrincipal: string | null | undefined,
  deps: ConnectorTurnDeps = {},
): boolean {
  const owner = ownerPrincipal?.trim();
  if (!owner) return false;
  if (owner === CRON_OPERATOR_OWNER) return true;
  // Only a contact can be the operator's own; nothing else needs the login read.
  if (!owner.startsWith("contact:")) return false;
  return cronOwnerActsAsOperator(owner, deps);
}

/**
 * The owner as the runner admits it for one fire, and the key of the
 * trigger's own session when the fire runs there (null when it runs anywhere
 * else). Pass no owner to admit nobody.
 */
export function captureTriggerRunAuthority(
  trigger: Pick<Trigger, "id" | "ownerPrincipal">,
  fire: { ownSessionKey: string | null },
  deps: ConnectorTurnDeps = {},
): TriggerRunAuthority {
  return {
    triggerId: trigger.id,
    ownerPrincipal: triggerRunsAs(trigger),
    ownerIsOperator: triggerOwnerActsAsOperator(trigger.ownerPrincipal, deps),
    ownSessionKey: fire.ownSessionKey || null,
  };
}

/**
 * The session an `isolated` trigger runs in, from the stored trigger: the
 * trigger's own session while a person owns it, the plain one-per-trigger
 * session otherwise. Losing the owner therefore moves the trigger to the
 * other session, and what its owner's turns read stays where no later fire
 * goes.
 */
export function triggerOwnSession(
  agentId: string,
  trigger: Pick<Trigger, "id" | "ownerPrincipal">,
): { sessionKey: string; own: boolean } {
  const own = isPersonPrincipal(trigger.ownerPrincipal);
  return { sessionKey: triggerIsolatedSessionKey(agentId, trigger.id, own), own };
}

/**
 * The session one fire of an `isolated` trigger runs in. The trigger's own
 * session holds what its owner's turns read and is continued by every later
 * one, so only a fire admitted as its owner's enters it. Any other fire (a
 * test by someone who is not the owner, a definition the runner has not
 * reloaded, a row that is gone) runs in the plain one-per-trigger session,
 * with nobody's authority: taking the authority from the turn alone would
 * still leave its prompt and its answer in the owner's history.
 */
export function triggerFireSession(
  agentId: string,
  trigger: Pick<Trigger, "id" | "ownerPrincipal">,
  fire: { asOwner: boolean },
): { sessionKey: string; own: boolean } {
  if (!fire.asOwner) return { sessionKey: triggerIsolatedSessionKey(agentId, trigger.id, false), own: false };
  return triggerOwnSession(agentId, trigger);
}

/**
 * The name of the session an `isolated` trigger runs in, once the runner has
 * created it, or null: its key for the own session, a generated name for the
 * session of a trigger nobody owns. How its owner finds it
 * (`ravi sessions read <name>`).
 */
export function triggerIsolatedSessionName(
  agentId: string,
  trigger: Pick<Trigger, "id" | "session" | "ownerPrincipal">,
  deps: { getSession?: (sessionKey: string) => { name?: string | null } | null | undefined } = {},
): string | null {
  if (trigger.session !== "isolated") return null;
  return (deps.getSession ?? getSession)(triggerOwnSession(agentId, trigger).sessionKey)?.name ?? null;
}

/**
 * Whether a trigger's fire may run in a session reached by a name, a key, a
 * template value or a reply session. A trigger's own session is entered only
 * by that trigger's `isolated` fires, which never come this way: nobody runs
 * a turn there by pointing another trigger at it.
 */
export function sessionAdmitsTriggerFire(session: { sessionKey: string } | null | undefined): boolean {
  return !isTriggerOwnSessionKey(session?.sessionKey);
}

/**
 * Why a trigger cannot be given this `--session`, or null: a literal name or
 * key that is another trigger's own session. Said when the trigger is
 * written, so it does not silently skip its fires later. A templated name is
 * resolved per event and skipped then.
 */
export function triggerSessionTargetError(
  ref: string,
  deps: { resolveSession?: (ref: string) => { sessionKey: string } | null | undefined } = {},
): string | null {
  const literal = ref.trim();
  if (!literal || isLegacySessionTarget(literal) || isSessionNameTemplate(literal)) return null;
  const session = (deps.resolveSession ?? resolveSession)(literal);
  // The session it resolves to, or, before that session exists, the name itself.
  const ownSession = !sessionAdmitsTriggerFire(session)
    ? session?.sessionKey
    : isTriggerOwnSessionKey(literal)
      ? literal
      : null;
  if (!ownSession) return null;
  return `Session ${literal} is the own session of trigger ${triggerOfSessionKey(ownSession)}: only that trigger's fires run there. Choose another session.`;
}

/**
 * Whether the trigger is set to run in a session of its own, the only place
 * Bases lends its owner's authority: `--session isolated`.
 */
export function triggerRunsInOwnSession(trigger: Pick<Trigger, "session">): boolean {
  return trigger.session === "isolated";
}

/**
 * The principal of the current turn, as a trigger owner: `operator` for the
 * terminal and the owner's own turns, else the turn's actor principal (the
 * cron rule).
 */
export function resolveTriggerOwnerForCurrentTurn(deps: ConnectorTurnDeps = {}): string {
  return resolveCronOwnerPrincipalForCurrentTurn(deps);
}

/**
 * Who a trigger keeps its owner for when it is turned on. Arming a trigger
 * is its owner's call, and the operator's: the operator may turn on a trigger
 * someone else drafted, which then still acts as that person, never as the
 * operator. Turned on by anyone else, it is left with no owner.
 */
export function ownerKeptOnEnable(
  trigger: Pick<Trigger, "ownerPrincipal">,
  setterOwner: string = resolveTriggerOwnerForCurrentTurn(),
): string | undefined {
  if (setterOwner === CRON_OPERATOR_OWNER) return trigger.ownerPrincipal?.trim() || undefined;
  return setterOwner;
}

/**
 * Whether the stored trigger is still what the runner subscribed: the fields
 * that decide what a fire runs, on which events and where it answers. An
 * edit the runner has not reloaded yet must not fire the old definition
 * under the row's current owner.
 */
export function sameTriggerDefinition(stored: Trigger, subscribed: Trigger): boolean {
  const definition = (trigger: Trigger) =>
    JSON.stringify([
      trigger.name,
      trigger.topic,
      trigger.message,
      trigger.messageSource ?? "manual",
      trigger.messageTemplateId ?? null,
      trigger.filter ?? null,
      trigger.agentId ?? null,
      trigger.accountId ?? null,
      trigger.session,
      trigger.replySession ?? null,
      trigger.replySource ?? null,
      trigger.executionType ?? "agent",
      trigger.debounceMs ?? 0,
      trigger.enabled,
    ]);
  return definition(stored) === definition(subscribed);
}

/**
 * The `triggers add` warning for an agent trigger whose turns do not act as
 * the operator in Bases, or null.
 */
export function triggerRunsAsWarning(
  trigger: Pick<Trigger, "id" | "ownerPrincipal" | "executionType">,
  deps: ConnectorTurnDeps = {},
): string | null {
  if (triggerOwnerActsAsOperator(trigger.ownerPrincipal, deps)) return null;
  const owner = triggerRunsAs(trigger);
  const lead = `Trigger ${trigger.id} runs as ${owner}, not the operator`;
  if ((trigger.executionType ?? "agent") !== "agent") {
    return `${lead}: a shell trigger runs only when its owner acts as the operator, so its next event turns it off without running the command (TRIGGER_SHELL_NOT_OPERATOR). The operator recreates it from their own chat with Ravi and removes this one.`;
  }
  if (owner.startsWith("contact:")) {
    return `${lead}: in Bases its turns act as that person through their own ravi link, never as the operator, and are refused while they have not linked (ACTOR_NOT_LINKED).`;
  }
  return `${lead}: Bases refuses its turns (ACTOR_UNKNOWN). Only the turn that creates a trigger owns it, so it has to be created from the turn of the person it should act for.`;
}

/**
 * The warning for an edit that took the owner away: someone other than the
 * owner changed the trigger, so it now acts as nobody.
 */
export function triggerOwnerLostWarning(
  before: Pick<Trigger, "id" | "ownerPrincipal" | "executionType">,
  after: Pick<Trigger, "ownerPrincipal">,
): string | null {
  if (!before.ownerPrincipal?.trim() || after.ownerPrincipal?.trim()) return null;
  const lead = `Trigger ${before.id} no longer runs as ${before.ownerPrincipal}: this change was not made by its owner, so the trigger now has no owner`;
  if ((before.executionType ?? "agent") !== "agent") {
    return `${lead}, and a shell trigger with no owner does not run (TRIGGER_SHELL_NOT_OPERATOR).`;
  }
  return `${lead} and Bases refuses its turns (ACTOR_UNKNOWN). The owner has to create it again to use Bases.`;
}
